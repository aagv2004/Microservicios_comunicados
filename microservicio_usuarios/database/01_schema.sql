
-- El script elimina la tabla usuarios y sus datos antes de recrear su estructura.
-- La ejecucion corresponde al esquema propietario del microservicio de Usuarios.
-- El esquema requiere CREATE TABLE, CREATE SEQUENCE y cuota en el tablespace DATA.
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE usuarios CASCADE CONSTRAINTS PURGE';
EXCEPTION
    WHEN OTHERS THEN
        -- La ausencia de la tabla permite continuar; los demas errores se propagan.
        IF SQLCODE != -942 THEN
            RAISE;
        END IF;
END;
/

CREATE TABLE usuarios (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR2(100 CHAR) NOT NULL,
    correo VARCHAR2(150 CHAR) NOT NULL,
    password_hash VARCHAR2(255 CHAR) NOT NULL,
    rol VARCHAR2(20 CHAR) NOT NULL,
    version NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT uk_usuarios_correo UNIQUE (correo),
    CONSTRAINT ck_usuarios_rol CHECK (rol IN ('USUARIO', 'ADMIN')),
    CONSTRAINT ck_usuarios_correo CHECK (correo = LOWER(TRIM(correo)))
);


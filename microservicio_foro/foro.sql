CREATE TABLE foro_categorias (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 6) PRIMARY KEY,
    nombre VARCHAR2(60 CHAR) NOT NULL,
    nombre_normalizado VARCHAR2(60 CHAR) NOT NULL,
    descripcion VARCHAR2(250 CHAR) NOT NULL,
    version NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT uk_foro_categoria_nombre UNIQUE (nombre_normalizado)
);

CREATE TABLE foro_temas (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 4) PRIMARY KEY,
    titulo VARCHAR2(150 CHAR) NOT NULL,
    contenido CLOB NOT NULL,
    categoria_id NUMBER(19) NOT NULL,
    autor_id NUMBER(19) NOT NULL,
    creado_en TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    actualizado_en TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    version NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT fk_foro_tema_categoria FOREIGN KEY (categoria_id) REFERENCES foro_categorias(id),
    CONSTRAINT ck_foro_tema_autor CHECK (autor_id > 0)
);

CREATE TABLE foro_comentarios (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY (START WITH 4) PRIMARY KEY,
    contenido CLOB NOT NULL,
    tema_id NUMBER(19) NOT NULL,
    autor_id NUMBER(19) NOT NULL,
    creado_en TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    actualizado_en TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    version NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT fk_foro_comentario_tema FOREIGN KEY (tema_id) REFERENCES foro_temas(id),
    CONSTRAINT ck_foro_comentario_autor CHECK (autor_id > 0)
);

CREATE INDEX ix_foro_tema_categoria ON foro_temas(categoria_id);
CREATE INDEX ix_foro_tema_autor ON foro_temas(autor_id);
CREATE INDEX ix_foro_comentario_tema ON foro_comentarios(tema_id);

